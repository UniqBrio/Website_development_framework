/**
 * ENGAGEMENT OPPORTUNITY REGISTRY — ECO §3, brief phase 4.
 *
 * METADATA ABOUT SUITABILITY, like the visual pattern registry: nothing here
 * selects anything. `decide.ts` reads it. A category is never recommended because
 * it is listed; it must pass all eleven hard gates and reach its minimum score.
 *
 * NO INDUSTRY NAME appears in this file, and the category shape has no industry
 * field (a test asserts both). Suitability is expressed through visitor tasks,
 * objectives, funnel stages, data and risk — the brief's "do not make industry
 * the dominant decision variable", enforced by construction, as
 * `objective-architecture.ts` already does for page architecture.
 *
 * EVIDENCE: every 0–5 value below is Tier E (framework policy): a reasoned
 * STARTING value, not a measured or published one. ECO §21 expects them to be
 * recalibrated only from validated outcome evidence, which does not exist yet.
 *
 * Only categories naming an `experiencePattern` have an implemented contract.
 * The rest are registry-only until the core system is validated (ECO §22).
 */
import type { OpportunityCategory, StaticAdequacyInput } from "./types.js";
import type { EngagementCategoryId } from "./vocabulary.js";

/** Defaults for the fields most categories share; each entry states what differs. */
function category(
  entry: Omit<
    OpportunityCategory,
    "minimumSuitability" | "approvalRequirements" | "acceptsInputFrom" | "inherentViolations" | "trivialisesSeriousDecisions" | "asksAbout" | "requiredContent"
  > &
    Partial<
      Pick<
        OpportunityCategory,
        "minimumSuitability" | "approvalRequirements" | "acceptsInputFrom" | "inherentViolations" | "trivialisesSeriousDecisions" | "asksAbout" | "requiredContent"
      >
    >,
): OpportunityCategory {
  return {
    minimumSuitability: 45,
    approvalRequirements: ["owner approval before the experience is published"],
    acceptsInputFrom: [],
    inherentViolations: [],
    trivialisesSeriousDecisions: false,
    asksAbout: [],
    requiredContent: [],
    ...entry,
  };
}

const adequateWhen = (condition: (i: StaticAdequacyInput) => boolean, yes: string, no: string) =>
  (input: StaticAdequacyInput) => (condition(input) ? { adequate: true, reason: yes } : { adequate: false, reason: no });

const fastPurchase = (i: StaticAdequacyInput) => i.purchaseCycle === "immediate" || i.purchaseCycle === "short";

